/**
 * Vendors the Kirtan Saathi matching engine into the Presenter frontend.
 *
 * Usage: node scripts/vendor-listen-engine.mjs <path to a kirtan-saathi checkout>
 *
 * Why vendored and not depended on: Kirtan Saathi is an application, not a published
 * package, and its engine is the part that has been benchmarked against real kirtan. Copying
 * the source at a pinned commit keeps that behaviour fixed until someone re-vendors on purpose
 * and re-runs the benchmark. See frontend/src/lib/listen/engine/VENDOR.md.
 *
 * The engine is TypeScript; Presenter's frontend is plain JavaScript with no TypeScript build.
 * So the files are transpiled once here (types removed, comments kept) and the JavaScript is
 * committed. Only two edits are made to the upstream source, both listed in PATCHES below.
 */
import { execFileSync } from 'node:child_process'
import { cpSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const TYPESCRIPT_VERSION = '5.6.3'

const FILES = [
  'gurmukhi.ts',
  'align.ts',
  'ngram-index.ts',
  'retrieval.ts',
  'tracker.ts',
  'paath.ts',
  'mode.ts',
  'engine.ts',
  'corpus.ts',
]

// The engine itself is pure: these edits only remove its two ties to Node and onnxruntime-node,
// which Presenter replaces with its own corpus loader and transcribers.
const AUDIO_TYPES = `/** Sample rate every transcriber receives audio at. */
export const SAMPLE_RATE = 16000;

/** What a transcriber returns for one window (see Kirtan Saathi src/engine/asr.ts). */
export interface AsrResult {
  pieces: string[];
  pieceTimes: Float32Array;
  text: string;
  key: string;
  keyTimes: Float32Array;
  frameSec: number;
  frames: number;
  windowSec: number;
  inferMs: number;
}
`

const PATCHES = {
  'engine.ts': source => source
    .replace( "import type { AsrResult } from './asr';", "import type { AsrResult } from './asr-types';" )
    .replace( "import { SAMPLE_RATE } from './asr';", "import { SAMPLE_RATE } from './asr-types';" ),
  'corpus.ts': source => source
    .replace( "import { readFileSync } from 'node:fs';\n", '' )
    .replace( "import { gunzipSync } from 'node:zlib';\n", '' )
    .replace( /\n {2}static load\(path: string\): Corpus \{[\s\S]*?\n {2}\}\n/, '\n' ),
}

const here = dirname( fileURLToPath( import.meta.url ) )
const outDir = resolve( here, '../frontend/src/lib/listen/engine' )
const upstream = resolve( process.argv[ 2 ] || '' )
const commit = execFileSync( 'git', [ '-C', upstream, 'rev-parse', 'HEAD' ] ).toString().trim()

const work = mkdtempSync( join( tmpdir(), 'listen-engine-' ) )
FILES.forEach( file => {
  const source = readFileSync( join( upstream, 'src/engine', file ), 'utf8' )
  const patch = PATCHES[ file ] || ( s => s )
  const patched = patch( source )
  if ( PATCHES[ file ] && patched === source ) throw new Error( `patch for ${file} no longer applies` )
  writeFileSync( join( work, file ), patched )
} )
writeFileSync( join( work, 'asr-types.ts' ), AUDIO_TYPES )

execFileSync( 'npx', [
  '--yes', `typescript@${TYPESCRIPT_VERSION}`, 'tsc',
  '--target', 'ES2020', '--module', 'ES2020', '--moduleResolution', 'node',
  '--lib', 'ES2022,DOM', '--strict', 'false', '--skipLibCheck', '--noEmitOnError', 'false',
  '--outDir', join( work, 'out' ),
  ...readdirSync( work ).filter( f => f.endsWith( '.ts' ) ).map( f => join( work, f ) ),
], { stdio: 'inherit' } )

const header = `// Vendored from Kirtan Saathi (MIT), https://github.com/sethigoldy/kirtan-saathi
// commit ${commit}, src/engine. Generated by apps/presenter/app/scripts/vendor-listen-engine.mjs.
// Do not edit by hand: change upstream or the script's PATCHES, then re-vendor.
`

rmSync( outDir, { recursive: true, force: true } )
cpSync( join( work, 'out' ), outDir, { recursive: true } )
readdirSync( outDir ).filter( f => f.endsWith( '.js' ) ).forEach( file => {
  const path = join( outDir, file )
  // Explicit extensions so the same files run under Node's ESM loader (tests) and webpack.
  const js = readFileSync( path, 'utf8' ).replace( /from '(\.\/[^']+)'/g, "from '$1.js'" )
  writeFileSync( path, `/* eslint-disable */\n${header}\n${js}` )
} )
writeFileSync( join( outDir, 'COMMIT' ), `${commit}\n` )
rmSync( work, { recursive: true, force: true } )
console.log( `vendored ${FILES.length} files from ${commit} into ${outDir}` )
